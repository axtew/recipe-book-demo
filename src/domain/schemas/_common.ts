import { z } from "zod";

// Примитивы, из которых собраны схемы сущностей. Ограничения повторяют check'и
// схемы базы и ничего сверх них не выдумывают: расхождение между тем, что
// пропускает форма, и тем, что примет Postgres, — это ошибка, которую видит
// пользователь уже после нажатия «Сохранить».

/** Название после обрезки пробелов; пустое не проходит. */
export const nameSchema = z.string().trim().min(1);

/** Ссылка на строку другой таблицы. */
export const idSchema = z.uuid();

/** Одно из четырёх чисел КБЖУ на 100 г. Null — цифры ещё не заполнены. */
export const nutrientPer100Schema = z.number().nonnegative().nullable();

/** Дата без времени, `YYYY-MM-DD`. Так она хранится в базе и так же живёт в приложении. */
export const dateSchema = z.iso.date();
